def _usage_values(response: Any) -> tuple[int, int, int, int]:
    usage: Mapping[str, Any] = {}
    llm_output = getattr(response, "llm_output", None)
    if isinstance(llm_output, Mapping):
        candidate = llm_output.get("token_usage") or llm_output.get("usage")
        if isinstance(candidate, Mapping):
            usage = candidate
    if not usage:
        for group in getattr(response, "generations", None) or []:
            for generation in group if isinstance(group, list) else [group]:
                candidate = getattr(
                    getattr(generation, "message", None),
                    "usage_metadata",
                    None,
                )
                if isinstance(candidate, Mapping):
                    usage = candidate
                    break
            if usage:
                break
    input_tokens = int(
        usage.get("prompt_tokens") or usage.get("input_tokens") or 0
    )
    output_tokens = int(
        usage.get("completion_tokens") or usage.get("output_tokens") or 0
    )
    total_tokens = int(usage.get("total_tokens") or 0)
    if not total_tokens:
        total_tokens = input_tokens + output_tokens
    cache_tokens = int(usage.get("precached_prompt_tokens") or 0)
    details = usage.get("input_token_details")
    if isinstance(details, Mapping):
        cache_tokens = int(details.get("cache_read") or cache_tokens)
    return input_tokens, output_tokens, total_tokens, cache_tokens


class JudgeTelemetry(BaseCallbackHandler):
    def __init__(self) -> None:
        super().__init__()
        self.run_ids: set[str] = set()
        self.completed = 0
        self.errors = 0
        self.input_tokens = 0
        self.output_tokens = 0
        self.total_tokens = 0
        self.cache_read_tokens = 0

    def on_chat_model_start(
        self,
        serialized: dict[str, Any],
        messages: list[list[Any]],
        *,
        run_id: Any,
        **kwargs: Any,
    ) -> None:
        del serialized, messages, kwargs
        self.run_ids.add(str(run_id))

    def on_llm_end(self, response: Any, *, run_id: Any, **kwargs: Any) -> None:
        del kwargs
        self.run_ids.add(str(run_id))
        usage = _usage_values(response)
        self.completed += 1
        self.input_tokens += usage[0]
        self.output_tokens += usage[1]
        self.total_tokens += usage[2]
        self.cache_read_tokens += usage[3]

    def on_llm_error(
        self,
        error: BaseException,
        *,
        run_id: Any,
        **kwargs: Any,
    ) -> None:
        del error, kwargs
        self.run_ids.add(str(run_id))
        self.errors += 1


def _judge(case: ReferenceCase, candidate: CandidateExchange, model: Any) -> Evaluation:
    telemetry = JudgeTelemetry()
    payload = {
        "query": case.query,
        "reference_answer": case.reference_answer,
        "candidate_http_status": candidate.http_status,
        "candidate_answer": candidate.answer,
        "candidate_display_results": candidate.display_results[:16_000],
        "candidate_error": candidate.error,
    }
    messages = [
        SystemMessage(content=JUDGE_PROMPT),
        HumanMessage(content=json.dumps(payload, ensure_ascii=False)),
    ]
    started_at = perf_counter()
    try:
        try:
            structured = model.with_structured_output(
                JudgeVerdict,
                method="function_calling",
            )
        except TypeError:
            structured = model.with_structured_output(JudgeVerdict)
        verdict = structured.with_retry(stop_after_attempt=3).invoke(
            messages,
            config={"callbacks": [telemetry]},
        )
        if not isinstance(verdict, JudgeVerdict):
            verdict = JudgeVerdict.model_validate(verdict)
        values = (
            verdict.status,
            verdict.score,
            verdict.reason,
            verdict.missing_requirements,
            verdict.contradictions,
        )
    except Exception as exc:
        values = (
            "judge_error",
            0,
            f"{type(exc).__name__}: {str(exc)[:500]}",
            [],
            [],
        )
    return Evaluation(
        scenario=case.scenario,
        status=values[0],
        score=values[1],
        reason=values[2],
        missing_requirements=list(values[3]),
        contradictions=list(values[4]),
        elapsed_seconds=perf_counter() - started_at,
        attempts=max(len(telemetry.run_ids), telemetry.completed + telemetry.errors),
        errors=telemetry.errors,
        input_tokens=telemetry.input_tokens,
        output_tokens=telemetry.output_tokens,
        total_tokens=telemetry.total_tokens,
        cache_read_tokens=telemetry.cache_read_tokens,
    )


def _reroute_count(metrics: Any) -> int:
    worker = sum(
        int(getattr(item, "routing_attempt", 0)) > 1
        for item in metrics.worker_routes
    )
    cycles = {
        int(step.get("cycle") or 0)
        for step in metrics.coordinator_plan
        if int(step.get("cycle") or 0) > 0
    }
    return worker + max(0, len(cycles) - 1)


def _worker_run(
    model: str,
    db_path: Path,
    output_path: Path,
    start_index: int = 0,
) -> int:
    """Private child process: import the app only after Ollama is configured."""

    os.environ.update(
        {
            "AGENT_RUN_METRICS_ENABLED": "1",
            "LLM_PROVIDER": "ollama",
            "OLLAMA_MODEL": model,
            "OLLAMA_TEMPERATURE": "0",
            "OLLAMA_REASONING": "0",
        }
    )
    os.environ.setdefault("OLLAMA_TIMEOUT", "240")

    import storage.database as db_storage

    db_storage.DB_PATH = str(db_path)
    from agents.run_metrics import consume_agent_run_metrics
    from app import app

    app.config.update(TESTING=True, CHAT_AGENT_MODE="multiagent")
    client = app.test_client()
    records: list[dict[str, Any]] = []
    if start_index and output_path.is_file():
        loaded = json.loads(output_path.read_text(encoding="utf-8"))
        if isinstance(loaded, list):
            records = list(loaded[:start_index])
    for case in REFERENCE_CASES[start_index:]:
        print(f"[{model}] {case.number}/7 {case.scenario}", flush=True)
        session_id = f"word9-local-{uuid4()}"
        started_at = perf_counter()
        try:
            response = client.post(
                "/chat",
                json={"query": case.query, "history": [], "session_id": session_id},
            )
            payload = response.get_json(silent=True)
            payload = payload if isinstance(payload, dict) else {}
            http_status = int(response.status_code)
            answer = str(payload.get("answer") or "")
            error = str(payload.get("error") or "")
            display_results = json.dumps(
                payload.get("display_items") or [],
                ensure_ascii=False,
                default=str,
            )
        except Exception as exc:
            http_status, answer, display_results = 0, "", "[]"
            error = f"{type(exc).__name__}: {exc}"
        wall_seconds = perf_counter() - started_at
        metrics = consume_agent_run_metrics(session_id)
        stages: dict[str, dict[str, int | float]] = {}
        if metrics is not None:
            for item in metrics.llm_stages:
                stages[item.stage] = {
                    "calls": item.calls,
                    "errors": item.error_calls,
                    "seconds": item.elapsed_seconds,
                    "input_tokens": item.input_tokens,
                    "output_tokens": item.output_tokens,
                    "total_tokens": item.total_tokens,
                    "cache_read_tokens": item.cache_read_tokens,
                }
        record = CandidateExchange(
            scenario=case.scenario,
            answer=answer,
            display_results=display_results,
            http_status=http_status,
            wall_seconds=wall_seconds,
            agent_seconds=(metrics.elapsed_seconds if metrics is not None else 0.0),
            llm_calls=(len(metrics.llm_calls) if metrics is not None else 0),
            tool_calls=(len(metrics.tool_calls) if metrics is not None else 0),
            tool_errors=(
                sum(item.has_error for item in metrics.tool_calls)
                if metrics is not None
                else 0
            ),
            reroutes=(_reroute_count(metrics) if metrics is not None else 0),
            input_tokens=(metrics.input_tokens if metrics is not None else 0),
            output_tokens=(metrics.output_tokens if metrics is not None else 0),
            total_tokens=(metrics.total_tokens if metrics is not None else 0),
            cache_read_tokens=(
                metrics.cache_read_tokens if metrics is not None else 0
            ),
            stage_usage=stages,
            error=error or (str(metrics.error or "") if metrics is not None else ""),
        )
        records.append(asdict(record))
        output_path.write_text(
            json.dumps(records, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
    return 0


def _run_model(
    model: str,
    db_path: Path,
    output_dir: Path,
    *,
    resume: bool,
    budget_seconds: float,
) -> tuple[list[CandidateExchange], float, int]:
    slug = "".join(character if character.isalnum() else "_" for character in model)
    working_db_path = output_dir / f"{slug.strip('_')}_fixture.db"
    output_path = output_dir / f"{slug.strip('_')}_exchanges.json"
    existing_raw: list[dict[str, Any]] = []
    if resume and output_path.is_file():
        loaded = json.loads(output_path.read_text(encoding="utf-8"))
        if isinstance(loaded, list):
            existing_raw = loaded
    if len(existing_raw) >= len(REFERENCE_CASES):
        records = [CandidateExchange(**item) for item in existing_raw]
        return records, sum(item.wall_seconds for item in records), 0
    if not resume or not working_db_path.is_file():
        shutil.copy2(db_path, working_db_path)
    spent_seconds = sum(
        float(item.get("wall_seconds") or 0.0) for item in existing_raw
    )
    remaining_seconds = max(1.0, budget_seconds - spent_seconds)
    command = [
        sys.executable,
        str(Path(__file__).resolve()),
        "--_worker-model",
        model,
        "--db",
        str(working_db_path),
        "--_worker-output",
        str(output_path),
        "--_start-index",
        str(len(existing_raw)),
    ]
    environment = os.environ.copy()
    environment.update(
        {
            "LLM_PROVIDER": "ollama",
            "OLLAMA_MODEL": model,
            "OLLAMA_TEMPERATURE": "0",
            "OLLAMA_REASONING": "0",
        }
    )
    started_at = perf_counter()
    try:
        completed = subprocess.run(
            command,
            cwd=PROJECT_ROOT,
            env=environment,
            check=False,
            timeout=remaining_seconds,
        )
        returncode = completed.returncode
    except subprocess.TimeoutExpired:
        returncode = 124
    elapsed = perf_counter() - started_at
    raw = (
        json.loads(output_path.read_text(encoding="utf-8"))
        if output_path.is_file()
        else []
    )
    return (
        [CandidateExchange(**item) for item in raw],
        spent_seconds + elapsed,
        returncode,
    )


